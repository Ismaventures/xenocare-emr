INSERT INTO procedure_catalogue (code, name, description, category, subcategory, nhis_price, base_price, requires_consent, requires_admission, created_at, updated_at)
SELECT np.code, np.name, 'NHIS: ' || np.name,
    CASE 
        WHEN LOWER(COALESCE(np.type,'')) LIKE '%surgical%' OR LOWER(np.name) LIKE '%surgery%' THEN 'surgical'
        WHEN LOWER(COALESCE(np.type,'')) LIKE '%laborator%' THEN 'diagnostic'
        WHEN LOWER(COALESCE(np.type,'')) LIKE '%radiolog%' THEN 'diagnostic'
        WHEN LOWER(COALESCE(np.type,'')) LIKE '%physiother%' THEN 'therapeutic'
        WHEN LOWER(np.name) LIKE '%biopsy%' THEN 'biopsy'
        WHEN LOWER(np.name) LIKE '%endoscop%' THEN 'endoscopy'
        ELSE 'other'
    END,
    np.type, np.price, np.price,
    CASE WHEN LOWER(COALESCE(np.type,'')) LIKE '%surgical%' THEN TRUE ELSE FALSE END,
    FALSE, NOW(), NOW()
FROM nhis_procedures np
WHERE NOT EXISTS (SELECT 1 FROM procedure_catalogue pc WHERE pc.code = np.code);

