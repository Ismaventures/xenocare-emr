-- PART 4: UPDATE PRICE_LIST
-- ============================================================================
INSERT INTO price_list (item_code, item_name, category, unit_price, is_active)
SELECT np.code, np.name,
    CASE WHEN np.type = 'General Description' THEN 'consultation'
         WHEN np.type LIKE '%Surgery%' THEN 'procedure'
         WHEN np.type LIKE '%Laboratory%' THEN 'laboratory'
         WHEN np.type LIKE '%Radiology%' THEN 'radiology'
         ELSE 'procedure' END,
    np.price, TRUE
FROM nhis_procedures np
ON CONFLICT (item_code) DO UPDATE SET item_name = EXCLUDED.item_name, unit_price = EXCLUDED.unit_price, updated_at = NOW();

-- ============================================================================
-- PART 5: CREATE UNIFIED PRICING VIEW
-- ============================================================================
CREATE OR REPLACE VIEW nhis_unified_pricing AS
SELECT np.code AS nhis_code, np.name AS procedure_name, np.type AS category,
       np.price AS nhis_price, pc.base_price AS facility_price,
       COALESCE(pc.id, np.id) AS procedure_id, 'nhis_procedures' AS source
FROM nhis_procedures np LEFT JOIN procedure_catalogue pc ON pc.code = np.code;

