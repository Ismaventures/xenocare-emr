-- =============================================================================
-- 222_security_linter_phase2_remediation.sql
-- Phase 2 remediation for Supabase security linter findings.
--
-- What this migration does:
-- 1) Sets an explicit search_path on public functions missing one.
-- 2) Moves pgvector extension out of public schema (to extensions schema).
-- 3) Replaces baseline authenticated ALL policies from migration 221 with
--    authenticated SELECT-only policies when paired service_role ALL exists.
-- 4) Tightens remaining non-SELECT permissive RLS policies by replacing
--    always-true predicates with authenticated-session checks.
--
-- Notes:
-- - This intentionally targets baseline policies generated by migration 221
--   (table_authenticated_all + table_service_role_all pairs).
-- - service_role policies are intentionally excluded from step 4.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1) Set immutable search_path for public functions missing one
-- -----------------------------------------------------------------------------
DO $$
DECLARE
  v_fn RECORD;
BEGIN
  FOR v_fn IN
    SELECT
      p.proname AS function_name,
      pg_get_function_identity_arguments(p.oid) AS identity_args
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND p.prokind = 'f'
      AND NOT EXISTS (
        SELECT 1
        FROM unnest(COALESCE(p.proconfig, ARRAY[]::text[])) AS cfg
        WHERE cfg LIKE 'search_path=%'
      )
      AND NOT EXISTS (
        SELECT 1
        FROM pg_depend d
        JOIN pg_extension e ON e.oid = d.refobjid
        WHERE d.classid = 'pg_proc'::regclass
          AND d.objid = p.oid
          AND d.deptype = 'e'
      )
  LOOP
    BEGIN
      EXECUTE format(
        'ALTER FUNCTION %I.%I(%s) SET search_path = pg_catalog, public, extensions',
        'public',
        v_fn.function_name,
        v_fn.identity_args
      );
    EXCEPTION
      WHEN insufficient_privilege THEN
        RAISE NOTICE 'Skipping function %.%(%): insufficient privilege', 'public', v_fn.function_name, v_fn.identity_args;
    END;
  END LOOP;
END
$$;

-- -----------------------------------------------------------------------------
-- 2) Move vector extension out of public schema
-- -----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS extensions;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM pg_extension e
    JOIN pg_namespace n ON n.oid = e.extnamespace
    WHERE e.extname = 'vector'
      AND n.nspname = 'public'
  ) THEN
    EXECUTE 'ALTER EXTENSION vector SET SCHEMA extensions';
  END IF;
END
$$;

-- -----------------------------------------------------------------------------
-- 3) Harden 221 baseline authenticated-all policies
-- -----------------------------------------------------------------------------
DO $$
DECLARE
  v_rec RECORD;
  v_auth_policy_name TEXT;
  v_service_policy_name TEXT;
  v_select_policy_name TEXT;
BEGIN
  FOR v_rec IN
    SELECT
      p.schemaname,
      p.tablename
    FROM pg_policies p
    WHERE p.schemaname = 'public'
      AND p.policyname = substr(p.tablename || '_authenticated_all', 1, 63)
      AND p.cmd = 'ALL'
      AND p.roles = '{authenticated}'::name[]
      AND COALESCE(p.qual, '') = 'true'
      AND COALESCE(p.with_check, '') = 'true'
      AND EXISTS (
        SELECT 1
        FROM pg_policies p2
        WHERE p2.schemaname = p.schemaname
          AND p2.tablename = p.tablename
          AND p2.policyname = substr(p.tablename || '_service_role_all', 1, 63)
          AND p2.cmd = 'ALL'
          AND p2.roles = '{service_role}'::name[]
      )
  LOOP
    v_auth_policy_name := substr(v_rec.tablename || '_authenticated_all', 1, 63);
    v_service_policy_name := substr(v_rec.tablename || '_service_role_all', 1, 63);
    v_select_policy_name := substr(v_rec.tablename || '_authenticated_select', 1, 63);

    -- Replace authenticated write-capable policy with read-only policy.
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON %I.%I',
      v_auth_policy_name,
      v_rec.schemaname,
      v_rec.tablename
    );

    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON %I.%I',
      v_select_policy_name,
      v_rec.schemaname,
      v_rec.tablename
    );

    EXECUTE format(
      'CREATE POLICY %I ON %I.%I FOR SELECT TO authenticated USING (true)',
      v_select_policy_name,
      v_rec.schemaname,
      v_rec.tablename
    );

    -- Ensure service_role baseline policy still exists for backend workflows.
    IF NOT EXISTS (
      SELECT 1
      FROM pg_policies p3
      WHERE p3.schemaname = v_rec.schemaname
        AND p3.tablename = v_rec.tablename
        AND p3.policyname = v_service_policy_name
    ) THEN
      EXECUTE format(
        'CREATE POLICY %I ON %I.%I FOR ALL TO service_role USING (true) WITH CHECK (true)',
        v_service_policy_name,
        v_rec.schemaname,
        v_rec.tablename
      );
    END IF;
  END LOOP;
END
$$;

-- -----------------------------------------------------------------------------
-- 4) Tighten remaining non-SELECT permissive policies (except service_role)
-- -----------------------------------------------------------------------------
DO $$
DECLARE
  v_pol RECORD;
  v_roles_sql TEXT;
  v_qual_is_true BOOLEAN;
  v_with_check_is_true BOOLEAN;
  v_new_using TEXT;
  v_new_with_check TEXT;
BEGIN
  FOR v_pol IN
    SELECT
      p.schemaname,
      p.tablename,
      p.policyname,
      p.roles,
      p.cmd,
      p.qual,
      p.with_check
    FROM pg_policies p
    WHERE p.schemaname = 'public'
      AND p.cmd IN ('ALL', 'INSERT', 'UPDATE', 'DELETE')
      AND NOT ('service_role' = ANY(p.roles))
  LOOP
    v_qual_is_true := COALESCE(v_pol.qual, '') ~* '^\s*\(?true\)?\s*$';
    v_with_check_is_true := COALESCE(v_pol.with_check, '') ~* '^\s*\(?true\)?\s*$';

    -- Skip policies that are already constrained for write operations.
    IF NOT (
      v_qual_is_true
      OR v_with_check_is_true
      OR (v_pol.cmd IN ('ALL', 'UPDATE') AND v_pol.with_check IS NULL AND v_qual_is_true)
    ) THEN
      CONTINUE;
    END IF;

    SELECT string_agg(
      CASE
        WHEN r = 'public' THEN 'PUBLIC'
        ELSE quote_ident(r)
      END,
      ', '
      ORDER BY r
    )
    INTO v_roles_sql
    FROM unnest(v_pol.roles) AS r;

    IF v_roles_sql IS NULL OR v_roles_sql = '' THEN
      v_roles_sql := 'PUBLIC';
    END IF;

    IF v_pol.cmd IN ('ALL', 'UPDATE', 'DELETE') THEN
      v_new_using := CASE
        WHEN v_qual_is_true THEN '(auth.uid() IS NOT NULL)'
        ELSE v_pol.qual
      END;
    ELSE
      v_new_using := NULL;
    END IF;

    IF v_pol.cmd IN ('ALL', 'UPDATE', 'INSERT') THEN
      v_new_with_check := CASE
        WHEN v_with_check_is_true THEN '(auth.uid() IS NOT NULL)'
        WHEN v_pol.cmd IN ('ALL', 'UPDATE') AND v_pol.with_check IS NULL AND v_qual_is_true THEN '(auth.uid() IS NOT NULL)'
        ELSE v_pol.with_check
      END;
    ELSE
      v_new_with_check := NULL;
    END IF;

    IF v_pol.cmd = 'INSERT' THEN
      EXECUTE format(
        'ALTER POLICY %I ON %I.%I TO %s WITH CHECK (%s)',
        v_pol.policyname,
        v_pol.schemaname,
        v_pol.tablename,
        v_roles_sql,
        COALESCE(v_new_with_check, 'auth.uid() IS NOT NULL')
      );
    ELSIF v_pol.cmd = 'DELETE' THEN
      EXECUTE format(
        'ALTER POLICY %I ON %I.%I TO %s USING (%s)',
        v_pol.policyname,
        v_pol.schemaname,
        v_pol.tablename,
        v_roles_sql,
        COALESCE(v_new_using, 'auth.uid() IS NOT NULL')
      );
    ELSE
      EXECUTE format(
        'ALTER POLICY %I ON %I.%I TO %s USING (%s) WITH CHECK (%s)',
        v_pol.policyname,
        v_pol.schemaname,
        v_pol.tablename,
        v_roles_sql,
        COALESCE(v_new_using, 'auth.uid() IS NOT NULL'),
        COALESCE(v_new_with_check, 'auth.uid() IS NOT NULL')
      );
    END IF;
  END LOOP;
END
$$;

COMMIT;
