-- =============================================================================
-- PART 2: CREATE VIEW FOR OUTGOING REFERRALS (for Encounter module)
-- =============================================================================

DROP VIEW IF EXISTS nhis_outgoing_referrals_view CASCADE;

CREATE VIEW nhis_outgoing_referrals_view AS
SELECT 
    -- Queue Info
    q.id AS queue_id,
    q.request_type,
    q.status AS queue_status,
    q.referral_direction,
    q.requested_at,
    q.processed_at,
    
    -- NHIS Referral Details (entered by NHIS officer)
    q.nhis_referral_code,
    q.referral_valid_from,
    q.referral_valid_to,
    CASE 
        WHEN q.referral_valid_to IS NOT NULL AND CURRENT_DATE > q.referral_valid_to 
        THEN TRUE 
        ELSE FALSE 
    END AS is_expired,
    
    -- Destination Facility
    q.destination_facility_name,
    q.destination_facility_nhis_id,
    q.destination_facility_address,
    
    -- Patient Bio Data
    p.id AS patient_id,
    p.patient_id AS file_number,
    p.emr_number,
    p.first_name,
    p.middle_name,
    p.surname,
    CONCAT_WS(' ', p.first_name, p.middle_name, p.surname) AS patient_full_name,
    p.date_of_birth,
    EXTRACT(YEAR FROM AGE(CURRENT_DATE, p.date_of_birth)) AS patient_age,
    p.gender,
    p.contact_phone,
    p.residential_address,
    
    -- Patient NHIS Info
    p.nhis_number,
    p.payer_info->>'scheme' AS hmo_code,
    p.payer_info->>'enrolee_id' AS nhis_id_no,
    
    -- Clinical Data (from doctor)
    q.chief_complaint AS clinical_findings,
    q.examination_findings,
    q.investigation_findings,
    q.provisional_diagnosis,
    q.diagnosis,
    q.clinical_basis AS reason_for_referral,
    q.clinical_notes,
    
    -- Referring Doctor Info
    rd.id AS referring_doctor_id,
    CONCAT_WS(' ', rd.first_name, rd.last_name) AS referring_doctor_name,
    rd.department AS referring_doctor_department,
    q.referring_doctor_signature,
    
    -- Source Encounter
    q.source_encounter_id,
    v.encounter_number,
    v.encounter_date,
    
    -- Print Info
    q.printed_at,
    q.printed_by,
    q.print_count,
    ps.first_name AS printed_by_first_name,
    ps.last_name AS printed_by_last_name,
    
    -- Approval Info
    q.processed_by,
    aps.first_name AS approved_by_first_name,
    aps.last_name AS approved_by_last_name,
    q.processing_notes AS approval_notes

FROM nhis_referral_queue q
LEFT JOIN patients p ON q.patient_id = p.id
LEFT JOIN staff rd ON q.requesting_doctor_id = rd.id
LEFT JOIN visits v ON q.source_encounter_id = v.id
LEFT JOIN staff ps ON q.printed_by = ps.id
LEFT JOIN staff aps ON q.processed_by = aps.id

WHERE q.referral_direction = 'outgoing'
ORDER BY 
    CASE q.status 
        WHEN 'approved' THEN 1  -- Ready to print
        WHEN 'pending' THEN 2   -- Awaiting approval
        WHEN 'completed' THEN 3 -- Already printed
        ELSE 4 
    END,
    q.requested_at DESC;

COMMENT ON VIEW nhis_outgoing_referrals_view IS 
'View for Encounter module External Referrals tab - shows approved outgoing NHIS referrals ready for printing';

-- =============================================================================
-- PART 3: CREATE VIEW FOR PENDING OUTGOING REFERRALS (for NHIS Desk)
-- =============================================================================

DROP VIEW IF EXISTS nhis_pending_outgoing_referrals CASCADE;

CREATE VIEW nhis_pending_outgoing_referrals AS
SELECT 
    q.id AS queue_id,
    q.status,
    q.urgency,
    q.requested_at,
    
    -- Patient Info
    p.id AS patient_id,
    p.patient_id AS file_number,
    CONCAT_WS(' ', p.first_name, p.middle_name, p.surname) AS patient_name,
    p.contact_phone,
    p.nhis_number,
    p.payer_info->>'scheme' AS hmo_scheme,
    p.payer_info->>'enrolee_id' AS hmo_enrolee_id,
    
    -- Clinical Summary
    q.provisional_diagnosis,
    q.clinical_basis AS reason_for_referral,
    
    -- Referring Doctor
    CONCAT_WS(' ', rd.first_name, rd.last_name) AS referring_doctor,
    
    -- Fields NHIS Officer needs to fill
    q.nhis_referral_code,
    q.destination_facility_name,
    q.destination_facility_nhis_id,
    q.referral_valid_from,
    q.referral_valid_to

FROM nhis_referral_queue q
LEFT JOIN patients p ON q.patient_id = p.id
LEFT JOIN staff rd ON q.requesting_doctor_id = rd.id

WHERE q.referral_direction = 'outgoing'
  AND q.status = 'pending'
ORDER BY 
    CASE q.urgency 
        WHEN 'Emergency' THEN 1 
        WHEN 'Urgent' THEN 2 
        ELSE 3 
    END,
    q.requested_at ASC;

COMMENT ON VIEW nhis_pending_outgoing_referrals IS 
'Pending outgoing referrals for NHIS desk officer to process (enter referral code and destination)';

