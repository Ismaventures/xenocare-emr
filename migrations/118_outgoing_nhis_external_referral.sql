-- =============================================================================
-- PART 5: CREATE FUNCTION TO PROCESS OUTGOING REFERRAL
-- This is called when NHIS officer approves and enters referral details
-- =============================================================================

CREATE OR REPLACE FUNCTION approve_outgoing_referral(
    p_queue_id UUID,
    p_nhis_referral_code VARCHAR(50),
    p_destination_facility_name VARCHAR(255),
    p_destination_facility_nhis_id VARCHAR(50) DEFAULT NULL,
    p_destination_facility_address TEXT DEFAULT NULL,
    p_referral_valid_from DATE DEFAULT CURRENT_DATE,
    p_referral_valid_to DATE DEFAULT NULL,
    p_processing_notes TEXT DEFAULT NULL,
    p_processed_by UUID DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_result JSONB;
    v_queue_record RECORD;
BEGIN
    -- Get the queue record
    SELECT * INTO v_queue_record
    FROM nhis_referral_queue
    WHERE id = p_queue_id AND referral_direction = 'outgoing';
    
    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Outgoing referral not found'
        );
    END IF;
    
    IF v_queue_record.status != 'pending' THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Referral is not in pending status'
        );
    END IF;
    
    -- Validate required fields
    IF p_nhis_referral_code IS NULL OR p_nhis_referral_code = '' THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'NHIS Referral Code is required'
        );
    END IF;
    
    IF p_destination_facility_name IS NULL OR p_destination_facility_name = '' THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Destination Facility Name is required'
        );
    END IF;
    
    -- Set default validity period (30 days if not specified)
    IF p_referral_valid_to IS NULL THEN
        p_referral_valid_to := p_referral_valid_from + INTERVAL '30 days';
    END IF;
    
    -- Update the queue record
    UPDATE nhis_referral_queue
    SET 
        status = 'approved',
        nhis_referral_code = p_nhis_referral_code,
        destination_facility_name = p_destination_facility_name,
        destination_facility_nhis_id = p_destination_facility_nhis_id,
        destination_facility_address = p_destination_facility_address,
        referral_valid_from = p_referral_valid_from,
        referral_valid_to = p_referral_valid_to,
        processing_notes = p_processing_notes,
        processed_by = p_processed_by,
        processed_at = NOW(),
        updated_at = NOW()
    WHERE id = p_queue_id;
    
    RETURN jsonb_build_object(
        'success', true,
        'message', 'Outgoing referral approved successfully',
        'queue_id', p_queue_id,
        'nhis_referral_code', p_nhis_referral_code,
        'destination_facility', p_destination_facility_name,
        'valid_until', p_referral_valid_to
    );
END;
$$;

COMMENT ON FUNCTION approve_outgoing_referral IS 
'Process outgoing NHIS referral: NHIS officer enters referral code and destination facility';

-- =============================================================================
-- PART 6: CREATE FUNCTION TO RECORD PRINT
-- =============================================================================

CREATE OR REPLACE FUNCTION record_referral_print(
    p_queue_id UUID,
    p_printed_by UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    UPDATE nhis_referral_queue
    SET 
        printed_at = NOW(),
        printed_by = p_printed_by,
        print_count = COALESCE(print_count, 0) + 1,
        status = CASE 
            WHEN status = 'approved' THEN 'completed'
            ELSE status 
        END,
        updated_at = NOW()
    WHERE id = p_queue_id;
    
    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Referral not found'
        );
    END IF;
    
    RETURN jsonb_build_object(
        'success', true,
        'message', 'Print recorded successfully',
        'queue_id', p_queue_id
    );
END;
$$;

COMMENT ON FUNCTION record_referral_print IS 
'Record when a referral form is printed and mark as completed';

