-- ============================================================================
-- OUTGOING NHIS EXTERNAL REFERRAL WORKFLOW
-- 
-- This migration implements the workflow for referring NHIS patients from
-- NDC Medical Centre to external hospitals:
-- 
-- Flow:
-- 1. Doctor creates outgoing external referral during consultation
-- 2. Request goes to NHIS Desk approval queue
-- 3. NHIS Officer enters referral code, destination facility, approves
-- 4. Approved referral routes to Encounter module "External Referrals" tab
-- 5. Staff can view details and PRINT professional referral form
-- ============================================================================

