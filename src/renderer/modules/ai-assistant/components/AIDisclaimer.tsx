/**
 * AIDisclaimer — persistent disclaimer banner for all AI-generated content.
 */
import React from 'react';
import { AlertTriangle } from 'lucide-react';

interface AIDisclaimerProps {
  compact?: boolean;
  className?: string;
}

export function AIDisclaimer({
  compact = false,
  className = '',
}: AIDisclaimerProps) {
  if (compact) {
    return (
      <p
        className={`text-xs text-amber-600 dark:text-amber-400 italic ${className}`}
      >
        <AlertTriangle className="inline w-3 h-3 mr-1" />
        AI-generated — requires clinical validation
      </p>
    );
  }

  return (
    <div
      className={`flex items-start gap-2 p-3 rounded-lg border border-amber-200 bg-amber-50 dark:bg-amber-900/20 dark:border-amber-700 ${className}`}
    >
      <AlertTriangle className="w-4 h-4 text-amber-600 dark:text-amber-400 mt-0.5 shrink-0" />
      <div className="text-xs text-amber-700 dark:text-amber-300">
        <p className="font-semibold">
          AI-Generated Content — Clinical Validation Required
        </p>
        <p className="mt-1">
          This content was generated by an AI assistant and is intended as a
          decision-support aid only. All clinical decisions must be made by
          qualified healthcare professionals. Always verify AI suggestions
          against institutional guidelines and clinical judgement.
        </p>
      </div>
    </div>
  );
}
